"""
Data extraction and ingestion module.
Provides adapters for local JSON files, public Brazilian open-source tools (radar-cnpj-mcp / mcp-dadosbr),
and live REST API queries to BrasilAPI.
"""

import json
import logging
import urllib.request
import urllib.error
from pathlib import Path
from typing import Dict, Any, List, Optional

from src.cleaner import clean_cnpj, normalize_company
from src.database import insert_company, save_cnaes, init_db
from src.config import get_target_cnaes, get_city_state
from src.digital_checker import enrich_company_digital

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")


def load_target_cnaes(cnaes_path: Optional[Path] = None) -> List[Dict[str, str]]:
    """Loads target CNAE definitions from config.json or fallback JSON file and persists to database."""
    cnaes = get_target_cnaes()
    if not cnaes:
        if cnaes_path is None:
            cnaes_path = Path(__file__).resolve().parent.parent / "data" / "cnaes_alvo.json"
        
        if cnaes_path.exists():
            with open(cnaes_path, "r", encoding="utf-8") as file:
                raw_cnaes = json.load(file)
                cnaes = [
                    {
                        "code": item["code"],
                        "description": item["description"],
                        "segment": item["segment"],
                    }
                    for item in raw_cnaes
                ]

    if cnaes:
        save_cnaes(cnaes)
    return cnaes


def load_local_seed_data(seed_path: Optional[Path] = None) -> int:
    """Reads structured local company records from JSON file and persists normalized rows into SQLite."""
    if seed_path is None:
        data_dir = Path(__file__).resolve().parent.parent / "data"
        candidate_local = data_dir / "seeds_londrina.json"
        candidate_sample = data_dir / "seeds_sample.json"
        seed_path = candidate_local if candidate_local.exists() else candidate_sample

    if not seed_path.exists():
        logging.error("Seed data file not found: %s", seed_path)
        return 0

    init_db()
    load_target_cnaes()

    with open(seed_path, "r", encoding="utf-8") as file:
        raw_companies = json.load(file)

    inserted_count = 0
    for raw in raw_companies:
        digital_info = enrich_company_digital(raw, check_http=False)
        raw.update(digital_info)
        normalized = normalize_company(raw)
        if insert_company(normalized):
            inserted_count += 1

    logging.info("Load complete: %d companies processed and saved to SQLite.", inserted_count)
    return inserted_count


def ingest_radar_cnpj_export(file_path: Path) -> int:
    """
    Adapter for processing JSON files generated by radar-cnpj-mcp.
    Maps heterogeneous keys into standardized schema and performs UPSERT into SQLite.
    """
    if not file_path.exists():
        logging.error("Radar-CNPJ export file not found: %s", file_path)
        return 0

    init_db()
    load_target_cnaes()

    default_city, default_state = get_city_state()

    with open(file_path, "r", encoding="utf-8") as file:
        data = json.load(file)

    records = data if isinstance(data, list) else data.get("empresas", [data])
    processed_count = 0

    for item in records:
        cnpj = item.get("cnpj") or item.get("cnpj_basico") or ""
        legal_name = item.get("razao_social") or item.get("nome") or ""
        trade_name = item.get("nome_fantasia") or item.get("fantasia") or ""
        cnae = item.get("cnae_fiscal") or item.get("cnae_principal") or item.get("cnae") or ""

        street = item.get("logradouro") or item.get("tipo_logradouro", "") + " " + item.get("logradouro", "")
        number = item.get("numero") or "S/N"
        neighborhood = item.get("bairro") or ""
        city = item.get("municipio") or item.get("cidade") or default_city
        state = item.get("uf") or item.get("estado") or default_state
        zip_code = item.get("cep") or ""

        phone = item.get("telefone") or item.get("ddd_telefone_1") or item.get("contato_telefonico") or ""
        email = item.get("email") or item.get("correio_eletronico") or ""
        status = item.get("situacao_cadastral") or item.get("descricao_situacao_cadastral") or "ACTIVE"

        adapted_record = {
            "cnpj": cnpj,
            "legal_name": legal_name,
            "trade_name": trade_name,
            "registration_status": status,
            "opening_date": item.get("data_abertura") or item.get("data_inicio_atividade") or "",
            "primary_cnae": cnae,
            "street": street,
            "number": number,
            "neighborhood": neighborhood,
            "city": city,
            "state": state,
            "zip_code": zip_code,
            "phone": phone,
            "email": email,
            "prospecting_status": item.get("status_prospeccao", "NEW"),
        }

        digital_info = enrich_company_digital(adapted_record, check_http=False)
        adapted_record.update(digital_info)

        normalized = normalize_company(adapted_record)
        if normalized["cnpj"] and insert_company(normalized):
            processed_count += 1

    logging.info("Radar-CNPJ / mcp-dadosbr integration: %d records ingested successfully.", processed_count)
    return processed_count


def fetch_brasil_api_cnpj(cnpj: str, timeout: int = 5) -> Optional[Dict[str, Any]]:
    """Queries live Brazilian public company registration data via BrasilAPI and persists result."""
    digits = clean_cnpj(cnpj)
    if len(digits) != 14:
        logging.warning("Invalid CNPJ for query: %s", cnpj)
        return None

    default_city, default_state = get_city_state()
    url = f"https://brasilapi.com.br/api/cnpj/v1/{digits}"
    headers = {"User-Agent": "LeadProspector-DataPipeline/1.0"}

    try:
        request = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(request, timeout=timeout) as response:
            if response.status == 200:
                data = json.loads(response.read().decode("utf-8"))

                secondary_codes = [str(item.get("codigo", "")) for item in data.get("cnaes_secundarios", [])]

                record = {
                    "cnpj": data.get("cnpj", digits),
                    "legal_name": data.get("razao_social", ""),
                    "trade_name": data.get("nome_fantasia", ""),
                    "registration_status": data.get("descricao_situacao_cadastral", "ACTIVE"),
                    "opening_date": data.get("data_inicio_atividade", ""),
                    "primary_cnae": str(data.get("cnae_fiscal", "")),
                    "secondary_cnaes": ",".join(secondary_codes),
                    "street": data.get("logradouro", ""),
                    "number": data.get("numero", ""),
                    "neighborhood": data.get("bairro", ""),
                    "city": data.get("municipio") or default_city,
                    "state": data.get("uf") or default_state,
                    "zip_code": str(data.get("cep", "")),
                    "phone": data.get("ddd_telefone_1", ""),
                    "email": data.get("email", ""),
                }

                digital_info = enrich_company_digital(record, check_http=True)
                record.update(digital_info)

                normalized = normalize_company(record)
                insert_company(normalized)
                return normalized
    except urllib.error.URLError as error:
        logging.warning("Could not connect to BrasilAPI for CNPJ %s: %s", cnpj, error.reason)
    except Exception as error:
        logging.error("Unexpected error querying CNPJ %s: %s", cnpj, error)

    return None
